export function normalizeComplexName(name = "") {
  return name
    .toLowerCase()
    .trim()
    .replace(/жилой\s+комплекс\s*/gi, "")
    .replace(/жк\s*/gi, "")
    .replace(/по\s+ул\.\s*/gi, "")
    .trim();
}

export function getExcelDefaults(name = "") {
  const norm = normalizeComplexName(name);
  if (EXCEL_COMPLEX_DEFAULTS[norm]) return EXCEL_COMPLEX_DEFAULTS[norm];
  for (const key of Object.keys(EXCEL_COMPLEX_DEFAULTS)) {
    if (key.length > 3 && (norm.includes(key) || key.includes(norm))) {
      return EXCEL_COMPLEX_DEFAULTS[key];
    }
  }
  return null;
}
